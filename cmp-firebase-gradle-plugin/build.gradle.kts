// ============================================================================
// MAVEN CENTRAL PUBLISHING CONFIGURATION
// ============================================================================
// GradlePlugin() also publishes the plugin MARKER artifact
// (io.github.mobilebytelabs.firebase:…gradle.plugin), which is what lets a
// consumer resolve `plugins { id("…") version "…" }` from Maven Central. No Gradle Plugin
// Portal account or release step is required — consumers only need mavenCentral() in their
// settings.gradle.kts `pluginManagement.repositories`, which nearly every KMP project has.
// Sign only where a key exists: CI exports ORG_GRADLE_PROJECT_signingInMemoryKey, and a
// human can opt in locally with -PsignPublications=true. Unconditional signAllPublications()
// makes `publishToMavenLocal` fail with "No configured signatory" on any dev machine, which
// blocks the one cheap way to verify a publication end-to-end before release.
val signPublications: Boolean =
    System.getenv("ORG_GRADLE_PROJECT_signingInMemoryKey") != null ||
        providers.gradleProperty("signPublications").orNull?.toBoolean() == true

mavenPublishing {
    coordinates(group.toString(), "cmp-firebase-gradle-plugin", version.toString())
    if (signPublications) {
        signAllPublications()
    }

    pom {
        name = "CMP Firebase Gradle Plugin"
        description =
            "Build-side setup enforcement for cmp-firebase — static Apple frameworks + Kotlin floor check."
        inceptionYear = "2026"
        url = "https://github.com/MobileByteLabs/KmpToolkit/"

        licenses {
            license {
                name = "The Apache License, Version 2.0"
                url = "https://www.apache.org/licenses/LICENSE-2.0.txt"
                distribution = "repo"
            }
        }

        developers {
            developer {
                id = "MobileByteLabs"
                name = "MobileByteLabs"
                url = "https://github.com/MobileByteLabs"
            }
        }

        scm {
            url = "https://github.com/MobileByteLabs/KmpToolkit/"
            connection = "scm:git:git://github.com/MobileByteLabs/KmpToolkit.git"
            developerConnection = "scm:git:ssh://git@github.com/MobileByteLabs/KmpToolkit.git"
        }
    }
}

tasks.withType<Sign>().configureEach {
    onlyIf { signPublications }
}
